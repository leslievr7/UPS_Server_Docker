#!/usr/bin/env python3
"""
Build app/static/icons/lucide.svg: an SVG sprite with only the icons the UI uses.

Lucide (https://lucide.dev, ISC licence) is shadcn's icon set. Keeping one small
sprite in the repo means the UI needs no internet connection and no icon font.

Usage (needs the lucide-static npm package unpacked somewhere):
    npm pack lucide-static && tar -xzf lucide-static-*.tgz
    python3 dev/tools/build_icons.py package/icons

Templates reference an icon as <svg><use href="/static/icons/lucide.svg#name"/></svg>,
normally through the icon() macro in app/templates/_ui.html.
"""

import os
import re
import sys

ICONS = [
    # brand and navigation
    'zap', 'layout-dashboard', 'settings', 'log-out', 'lock', 'key-round', 'shield-check',
    # theme
    'sun', 'moon', 'laptop',
    # power and machines
    'plug-zap', 'unplug', 'power', 'power-off', 'server', 'hard-drive', 'monitor', 'cpu',
    'radio-tower', 'activity', 'battery-charging', 'battery-full', 'battery-low',
    'battery-warning', 'flask-conical', 'send', 'wrench', 'wifi-off',
    # status
    'circle-check', 'circle-alert', 'triangle-alert', 'circle-x', 'info', 'loader-circle',
    'clock', 'timer', 'history', 'calendar-clock', 'circle-dot',
    # actions
    'plus', 'pencil', 'trash-2', 'refresh-cw', 'x', 'chevron-down', 'copy', 'mail', 'bell',
    'eye', 'eye-off',
]

REPO = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
OUTPUT = os.path.join(REPO, 'app', 'static', 'icons', 'lucide.svg')


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    source = sys.argv[1]
    symbols = []
    for name in ICONS:
        with open(os.path.join(source, f'{name}.svg')) as f:
            svg = f.read()
        body = re.search(r'<svg[^>]*>(.*)</svg>', svg, re.S).group(1)
        body = re.sub(r'<!--.*?-->', '', body, flags=re.S)
        body = re.sub(r'\s+', ' ', body).strip()
        symbols.append(f'<symbol id="{name}" viewBox="0 0 24 24">{body}</symbol>')

    with open(OUTPUT, 'w') as f:
        f.write('<svg xmlns="http://www.w3.org/2000/svg" style="display:none">\n'
                '<!-- Lucide icons (ISC licence, see LICENSE.txt). '
                'Generated by dev/tools/build_icons.py. -->\n')
        f.write('\n'.join(symbols))
        f.write('\n</svg>\n')
    print(f"Wrote {len(symbols)} icons to {OUTPUT} ({os.path.getsize(OUTPUT)} bytes)")


if __name__ == '__main__':
    main()
